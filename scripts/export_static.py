"""Build the no-server version in docs/ (served by GitHub Pages).

Copies the shared frontend files and writes docs/data.js from the same catalog the
Python app uses, run through the same pipeline. Re-run after changing the catalog:

    python scripts/export_static.py
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.catalog import (  # noqa: E402
    ADAPTIVE_ONLY, CATALOG, CITIES, SCOPE_NATIONAL, SCOPE_REGIONAL_KM, SCOPE_RESOURCE, TYPE_COLORS,
)
from app.pipeline import run  # noqa: E402

DOCS = ROOT / "docs"


def data_js() -> str:
    rows = run([{**c, "source": "catalog"} for c in CATALOG])["rows"]
    payload = {
        "catalog": rows,
        "cities": CITIES,
        "typeColors": TYPE_COLORS,
        "scopeNational": sorted(SCOPE_NATIONAL),
        "scopeRegionalKm": SCOPE_REGIONAL_KM,
        "scopeResource": sorted(SCOPE_RESOURCE),
        "adaptiveOnly": sorted(ADAPTIVE_ONLY),
    }
    return "// Generated by scripts/export_static.py. Do not edit by hand.\nwindow.PLAYPATH_DATA = " + json.dumps(
        payload, ensure_ascii=False, indent=1
    ) + ";\n"


def main() -> None:
    (DOCS / "vendor").mkdir(parents=True, exist_ok=True)
    (DOCS / "data.js").write_text(data_js(), encoding="utf-8")
    for name in ("app.js", "styles.css", "app-pages.css"):
        shutil.copy2(ROOT / "static" / name, DOCS / name)
    for f in (ROOT / "static" / "vendor").iterdir():
        shutil.copy2(f, DOCS / "vendor" / f.name)
    (DOCS / ".nojekyll").write_text("")
    print(f"wrote {DOCS}")


if __name__ == "__main__":
    main()
